/**
 * Transforms raw 2D row data (e.g. from Google Sheets API values / CSV)
 * into typed SiavongaParticipant objects.
 */
export function parseSheetRows(rows: any[][]): SiavongaParticipant[] {
  if (!rows || rows.length <= 1) return [];

  // Check if first row is header
  const dataRows = (rows[0][1] && String(rows[0][1]).toLowerCase().includes('email'))
    ? rows.slice(1)
    : rows;

  return dataRows
    .filter((row) => row && row.length > 1 && row[1]) // Must have an email address
    .map((row, index) => {
      const amountRaw = row[8] !== undefined ? String(row[8]).replace(/[^0-9.]/g, '') : '0';
      const amountPaid = parseFloat(amountRaw) || 0;

      return {
        timestamp: row[0] ? String(row[0]).trim() : new Date().toISOString(),
        email: row[1] ? String(row[1]).trim() : `participant_${index + 1}@tempofit.zm`,
        fullName: row[2] ? String(row[2]).trim() : 'Participant',
        phoneNumber: row[3] ? String(row[3]).trim() : 'N/A',
        townCity: row[4] ? String(row[4]).trim() : 'Lusaka',
        isTempoFitMember: row[5] ? String(row[5]).trim() : 'No',
        categoryPackage: row[6] ? String(row[6]).trim() : 'K150 - Run Only',
        transactionReference: row[7] ? String(row[7]).trim() : 'N/A',
        amountPaid,
        emergencyContact: row[9] ? String(row[9]).trim() : 'N/A',
        medicalConditions: row[10] ? String(row[10]).trim() : 'None',
        memberVerificationStatus: row[11] ? String(row[11]).trim() : 'N/A - Public',
        registrationNumber: row[12] ? String(row[12]).trim() : `TF-SIAV-${String(index + 1).padStart(4, '0')}`,
        paymentVerificationStatus: row[13] ? String(row[13]).trim() : 'Pending',
        miniDripKitEntitlement: row[14] ? String(row[14]).trim() : 'NO',
        manualApproval: row[15] ? String(row[15]).trim() : 'Pending',
        confirmationStatus: row[16] ? String(row[16]).trim() : 'Stage 1 Sent',
      };
    });
}
